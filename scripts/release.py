#!/usr/bin/env python3
"""Build release archives, a Homebrew formula, and checksums into dist/<tag>/.

Usage: scripts/release.py v0.1.0
The tap (cross-entropy-ai/homebrew-tap) imports moop.rb from the latest
release after checking it against checksums.txt.
"""

import argparse
import gzip
import hashlib
import io
import os
from pathlib import Path
import re
import subprocess
import tarfile

ROOT = Path(__file__).resolve().parent.parent
REPOSITORY = "https://github.com/cross-entropy-ai/moop"
TARGETS = [(s, a) for s in ("darwin", "linux") for a in ("amd64", "arm64")]


def build(tag: str, destination: Path) -> None:
    if not re.fullmatch(r"v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", tag):
        raise ValueError("Expected a stable version tag such as v0.1.0")
    version = tag[1:]
    destination.mkdir(parents=True, exist_ok=True)
    checksums = {}
    for system, arch in TARGETS:
        name = f"moop_{system}_{arch}.tar.gz"
        binary = destination / f"moop-{system}-{arch}"
        env = dict(os.environ, CGO_ENABLED="0", GOOS=system, GOARCH=arch)
        subprocess.run(
            ["go", "build", "-trimpath", "-buildvcs=false",
             f"-ldflags=-s -w -X main.version={version}", "-o", str(binary), "."],
            cwd=ROOT, env=env, check=True,
        )
        # Fixed metadata keeps archives reproducible across build hosts.
        with (destination / name).open("wb") as output:
            with gzip.GzipFile(filename="", fileobj=output, mode="wb", mtime=0) as zipped:
                with tarfile.open(fileobj=zipped, mode="w") as archive:
                    for filename, data, mode in (
                        ("moop", binary.read_bytes(), 0o755),
                        ("README.md", (ROOT / "README.md").read_bytes(), 0o644),
                        ("LICENSE", (ROOT / "LICENSE").read_bytes(), 0o644),
                    ):
                        entry = tarfile.TarInfo(filename)
                        entry.size = len(data)
                        entry.mode = mode
                        archive.addfile(entry, io.BytesIO(data))
        binary.unlink()
        checksums[name] = hashlib.sha256((destination / name).read_bytes()).hexdigest()
        print(f"Built {name}", flush=True)

    lines = [
        "# Generated by moop's release workflow. Do not edit manually.",
        "class Moop < Formula",
        '  desc "Transcribe audio from the terminal; companion to Meep"',
        f'  homepage "{REPOSITORY}"',
        f'  version "{version}"',
        '  license "MIT"',
    ]
    for system, block in (("darwin", "on_macos"), ("linux", "on_linux")):
        lines += ["", f"  {block} do", "    if Hardware::CPU.arm?"]
        for arch in ("arm64", "amd64"):
            name = f"moop_{system}_{arch}.tar.gz"
            if arch == "amd64":
                lines.append("    else")
            lines += [f'      url "{REPOSITORY}/releases/download/{tag}/{name}"',
                      f'      sha256 "{checksums[name]}"']
        lines += ["    end", "  end"]
    lines += ["", "  def install", '    bin.install "moop"', "  end", "", "  test do",
              '    assert_equal version.to_s, shell_output("#{bin}/moop version").strip',
              "  end", "end", ""]
    formula = destination / "moop.rb"
    formula.write_text("\n".join(lines))
    checksums[formula.name] = hashlib.sha256(formula.read_bytes()).hexdigest()
    (destination / "checksums.txt").write_text(
        "".join(f"{checksum}  {name}\n" for name, checksum in sorted(checksums.items()))
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tag", help="Stable version tag, e.g. v0.1.0")
    args = parser.parse_args()
    try:
        build(args.tag, ROOT / "dist" / args.tag)
    except ValueError as error:
        parser.error(str(error))
